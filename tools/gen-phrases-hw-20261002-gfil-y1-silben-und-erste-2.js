#!/usr/bin/env node
/* Write the two phrase files of Ma Mi Mo straight out of the game.
 *
 * Every line the game can say is built in one block of
 * hw-20261002-gfil-y1-silben-und-erste-2/index.html marked TEXT-CORE. That
 * block touches no DOM, so it can be run here and asked for its own phrase
 * list: { en: [...], de: [...] }. English lines are rendered with the default
 * voice, German pieces (as respelled by DE_CLIP) with Katja via the header.
 * Change a word in the game, re-run this, re-run tools/build-audio.py once
 * per game, and the clips follow:
 *
 *   node tools/gen-phrases-hw-20261002-gfil-y1-silben-und-erste-2.js
 *   tools/build-audio.py --game hw-20261002-gfil-y1-silben-und-erste-2
 *   tools/build-audio.py --game hw-20261002-gfil-y1-silben-und-erste-2-de
 */
'use strict';

var fs = require('fs');
var path = require('path');

var NAME = 'hw-20261002-gfil-y1-silben-und-erste-2';
var ROOT = path.dirname(__dirname);
var GAME = path.join(ROOT, NAME, 'index.html');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);

var core = src.slice(start, end);
var lists = new Function(core + '\nreturn phraseList();')();

function write(file, header, phrases) {
  var out = path.join(ROOT, 'tools', 'phrases', file);
  fs.writeFileSync(out, header.concat(phrases).join('\n') + '\n', 'utf8');
  console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, out));
}

var about = [
  '# GENERATED by tools/gen-phrases-' + NAME + '.js from the TEXT-CORE block',
  '# in ' + NAME + '/index.html. Edit the game, not this file.',
  ''
];

write(NAME + '.txt', [
  '# ' + NAME + ' — the English lines, already split into the segments the',
  '# runtime plays one after another (en-GB Sonia, the default voice).'
].concat(about), lists.en);

write(NAME + '-de.txt', [
  '# voice: de-DE-KatjaNeural',
  '# ' + NAME + '-de — the German syllables and words, as respelled by DE_CLIP',
  '# in the game (the manifest key is the respelling).'
].concat(about), lists.de);
