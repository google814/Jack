#!/usr/bin/env node
/* Write tools/phrases/big-numbers.txt straight out of the game.
 *
 * Every line Jack's Big Numbers can say is built in one block of
 * big-numbers/index.html marked TEXT-CORE — the number words, the sixty
 * problems and the three sentences each of them produces. That block touches
 * no DOM, so it can be run here and asked for its own phrase list. Change a
 * sum in the game, re-run this, re-run tools/build-audio.py, and the clips
 * follow.
 *
 *   node tools/gen-phrases-big-numbers.js
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.dirname(__dirname);
var GAME = path.join(ROOT, 'big-numbers', 'index.html');
var OUT = path.join(ROOT, 'tools', 'phrases', 'big-numbers.txt');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);

var core = src.slice(start, end);
var phrases = new Function(core + '\nreturn phraseList();')();

var header = [
  '# big-numbers — every line the game speaks, already split into the',
  '# segments the runtime plays one after another.',
  '# GENERATED by tools/gen-phrases-big-numbers.js from the TEXT-CORE block',
  '# in big-numbers/index.html. Edit the game, not this file.',
  ''
];

fs.writeFileSync(OUT, header.concat(phrases).join('\n') + '\n', 'utf8');
console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, OUT));
