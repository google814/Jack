#!/usr/bin/env node
/* Write tools/phrases/ten-frames.txt straight out of the game.
 *
 * Every line Jack's Ten Frames can say is built in one block of
 * ten-frames/index.html marked TEXT-CORE — the forty sums and the hints and
 * sentences each of them produces. That block touches no DOM, so it can be
 * run here and asked for its own phrase list.
 * Change a sum in the game, re-run this, re-run tools/build-audio.py, and
 * the clips follow.
 *
 *   node tools/gen-phrases-ten-frames.js
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.dirname(__dirname);
var GAME = path.join(ROOT, 'ten-frames', 'index.html');
var OUT = path.join(ROOT, 'tools', 'phrases', 'ten-frames.txt');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);

var core = src.slice(start, end);
var phrases = new Function(core + '\nreturn phraseList();')();

var header = [
  '# ten-frames — every line the game speaks, already split into the',
  '# segments the runtime plays one after another.',
  '# GENERATED by tools/gen-phrases-ten-frames.js from the TEXT-CORE block',
  '# in ten-frames/index.html. Edit the game, not this file.',
  ''
];

fs.writeFileSync(OUT, header.concat(phrases).join('\n') + '\n', 'utf8');
console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, OUT));
