#!/usr/bin/env node
/* Write tools/phrases/hw-20260926-capital-letters.txt straight out of the game.
 *
 * Every line "Write it Right!" can say is built in the TEXT-CORE block of
 * hw-20260926-capital-letters/index.html. That block touches no DOM, so it is
 * run here, and each line is split into the same segments the game plays.
 *
 *   node tools/gen-phrases-hw-20260926-capital-letters.js
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.dirname(__dirname);
var NAME = 'hw-20260926-capital-letters';
var GAME = path.join(ROOT, NAME, 'index.html');
var OUT = path.join(ROOT, 'tools', 'phrases', NAME + '.txt');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);
var lines = new Function(src.slice(start, end) + '\nreturn phraseList();')();

/* the game's segments(): split after . ! ? : followed by a space */
function segments(text) {
  var t = String(text).replace(/\s+/g, ' ').trim(), out = [], buf = '', i = 0;
  while (i < t.length) {
    var ch = t.charAt(i);
    buf += ch; i++;
    if ((ch === '.' || ch === '!' || ch === '?' || ch === ':') && /\s/.test(t.charAt(i))) {
      while (i < t.length && /\s/.test(t.charAt(i))) i++;
      if (buf.trim()) out.push(buf.trim());
      buf = '';
    }
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

var seen = {}, phrases = [];
lines.forEach(function (l) {
  segments(l).forEach(function (s) { if (!seen[s]) { seen[s] = 1; phrases.push(s); } });
});

var header = [
  '# ' + NAME + ' — every line the game speaks, already split into the',
  '# segments the runtime plays one after another.',
  '# GENERATED by tools/gen-phrases-' + NAME + '.js from the TEXT-CORE block',
  '# in ' + NAME + '/index.html. Edit the game, not this file.',
  ''
];
fs.writeFileSync(OUT, header.concat(phrases).join('\n') + '\n', 'utf8');
console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, OUT));
