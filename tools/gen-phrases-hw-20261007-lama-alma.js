#!/usr/bin/env node
/* Write tools/phrases/hw-20261007-lama-alma.txt straight out of the game.
 *
 * Every line Lama Alma can say is built in one block of
 * hw-20261007-lama-alma/index.html marked TEXT-CORE: the seven words, their
 * syllables, the picture words and the German lines. That block touches no
 * DOM, so it can be run here and asked for its own phrase list.
 * Change a word in the game, re-run this, re-run tools/build-audio.py
 * (--voice de-DE-KatjaNeural), and the clips follow.
 *
 *   node tools/gen-phrases-hw-20261007-lama-alma.js
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.dirname(__dirname);
var GAME = path.join(ROOT, 'hw-20261007-lama-alma', 'index.html');
var OUT = path.join(ROOT, 'tools', 'phrases', 'hw-20261007-lama-alma.txt');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);

var core = src.slice(start, end);
var phrases = new Function(core + '\nreturn phraseList();')();

var header = [
  '# hw-20261007-lama-alma — every line the game speaks, already split into the',
  '# segments the runtime plays one after another.',
  '# GENERATED by tools/gen-phrases-hw-20261007-lama-alma.js from the TEXT-CORE block',
  '# in hw-20261007-lama-alma/index.html. Edit the game, not this file.',
  ''
];

fs.writeFileSync(OUT, header.concat(phrases).join('\n') + '\n', 'utf8');
console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, OUT));
