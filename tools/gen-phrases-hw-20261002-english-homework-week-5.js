#!/usr/bin/env node
/* Write tools/phrases/hw-20261002-english-homework-week-5.txt straight out of the game.
 *
 * Every line Tin Dog's Words can say is built in one block of
 * hw-20261002-english-homework-week-5/index.html marked TEXT-CORE: the eleven
 * words, their meanings and sentences, and the match lines. That block touches
 * no DOM, so it can be run here and asked for its own phrase list.
 * Change a word in the game, re-run this, re-run tools/build-audio.py
 * (--voice en-GB-SoniaNeural), and the clips follow.
 *
 *   node tools/gen-phrases-hw-20261002-english-homework-week-5.js
 */
'use strict';

var fs = require('fs');
var path = require('path');

var ROOT = path.dirname(__dirname);
var GAME = path.join(ROOT, 'hw-20261002-english-homework-week-5', 'index.html');
var OUT = path.join(ROOT, 'tools', 'phrases', 'hw-20261002-english-homework-week-5.txt');

var src = fs.readFileSync(GAME, 'utf8');
var start = src.indexOf('/* ==== TEXT-CORE ====');
var end = src.indexOf('/* ==== END TEXT-CORE ==== */');
if (start < 0 || end < 0) throw new Error('TEXT-CORE markers not found in ' + GAME);

var core = src.slice(start, end);
var phrases = new Function(core + '\nreturn phraseList();')();

var header = [
  '# voice: en-GB-SoniaNeural',
  '# hw-20261002-english-homework-week-5 — every line the game speaks, already split into the',
  '# segments the runtime plays one after another.',
  '# GENERATED by tools/gen-phrases-hw-20261002-english-homework-week-5.js from the TEXT-CORE block',
  '# in hw-20261002-english-homework-week-5/index.html. Edit the game, not this file.',
  ''
];

fs.writeFileSync(OUT, header.concat(phrases).join('\n') + '\n', 'utf8');
console.log(phrases.length + ' phrases -> ' + path.relative(ROOT, OUT));
